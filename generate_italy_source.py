#!/usr/bin/env python3
"""
Generate the new italy_bot_server.py based on the Macau template.
Write it to /tmp/italy_bot_server_new.py for review, then we'll deploy it.
"""
import os
import hashlib

# Read the Macau template
macau_path = "/opt/xrplme/thoughts/api/macau_bot_server.py"
with open(macau_path) as f:
    content = f.read()

# Italy-specific substitutions
replacements = [
    # Country name and display
    ('COUNTRY_NAME = "macau"', 'COUNTRY_NAME = "italy"'),
    ('COUNTRY_CAP = "Macau"', 'COUNTRY_CAP = "Italy"'),
    
    # Base directory and data file
    ('BASE_DIR = Path("/opt/xrplme/thoughts/api/mo-agent-full/publication")', 
     'BASE_DIR = Path("/opt/xrplme/thoughts/api/italy-agent-full/publication")'),
    
    # Docstring
    ('Macau Policy Data API - FastAPI + x402 payment gateway.',
     'Italy Bot Server - x402 payment gateway'),
    ('Auto-generated by Country Factory.',
     'Port: 8117 | Country: Italy (italy, ISO: IT)'),
    
    # X402 config
    ('"description": "Macau policy data API access"',
     '"description": "Italy policy data API access"'),
    ('"description": "Macau AI analysis query"',
     '"description": "Italy AI analysis query"'),
    
    # Placeholder data
    ('"title": "Macau Economic Overview"', '"title": "[ITALY] Economic Overview"'),
    ('"Macau Economic Overview"', '"Italy Economic Overview"'),
    ('"meta_description": "Macau policy and economic data', '"meta_description": "Italy policy and economic data'),
    ('"policy_topics": ["economy", "trade", "business"]', '"policy_topics": ["economy", "trade", "business"]'),
    ('"https://example.com/macau-data"', '"https://example.com/italy-data"'),
    ('"source_name": "Placeholder Data"', '"source_name": "Placeholder Data"'),
    
    # API route paths
    ('path="/api/v1/macau/bot"', 'path="/api/v1/italy/bot"'),
    ('path="/api/v1/macau/bot/ai"', 'path="/api/v1/italy/bot/ai"'),
    ('/api/v1/macau/bot"', '/api/v1/italy/bot"'),
    ('/api/v1/macau/bot/ai"', '/api/v1/italy/bot/ai"'),
    
    # Endpoint descriptions
    ('Macau policy data API access (0.1 XRP)', 'Italy policy data API access (0.1 XRP)'),
    ('Macau AI analysis query', 'Italy AI analysis query'),
    
    # Bot response messages
    ('No Macau policy data found', 'No Italy policy data found'),
    ('Available: economy, trade, business, policy.', 'Available: economy, trade, business, policy.'),
    
    # AI system prompts
    ('You are an AI policy analyst for Macau.', 'You are an AI policy analyst for Italy.'),
    
    # FastAPI title
    ('app = FastAPI(title="Macau Policy Data API", version="1.0.0")',
     'app = FastAPI(title="Italy Policy Data API", version="1.0.0")'),
    
    # Health endpoint country
    ('"country": "macau"', '"country": "italy"'),
    
    # Error messages
    ('"Error: Macau data not available.', '"Error: Italy data not available.'),
    
    # format_response
    ('No Macau policy data found for', 'No Italy policy data found for'),
    ('Macau policy data', 'Italy policy data'),
    
    # uvicorn run
    ('uvicorn.run(app, host="0.0.0.0", port=8109)',
     'uvicorn.run(app, host="0.0.0.0", port=8117)'),
    
    # Main block
    ('Main bot endpoint - Macau policy data', 'Main bot endpoint - Italy policy data'),
    ('Main bot endpoint - Macau', 'Main bot endpoint - Italy'),
]

# Also fix the docstring title line
content = content.replace(
    'Macau Policy Data API - FastAPI + x402 payment gateway.',
    'Italy Bot Server - x402 payment gateway'
)
content = content.replace(
    'POST /api/v1/macau/bot',
    'POST /api/v1/italy/bot'
)

for old, new in replacements:
    if old in content:
        content = content.replace(old, new)
    else:
        print(f"WARNING: '{old}' not found in template")

# Verify critical replacements
checks = [
    ('COUNTRY_NAME = "italy"', 'Country name set'),
    ('COUNTRY_CAP = "Italy"', 'Country cap set'),
    ('/opt/xrplme/thoughts/api/italy-agent-full', 'Data path set'),
    ('/api/v1/italy/bot', 'API path in options set'),
    ('port=8117', 'Port set'),
    ('Italy Policy Data API access', 'Description set'),
    ('title="Italy Policy Data API"', 'FastAPI title set'),
    ('razjTyzT6gBVH86iduU8HuEiZ2YUorNQj8', 'Collector address preserved'),
    ('from x402_xrpl.server import require_x402', 'x402_xrpl import present'),
    ('from sqlite_invoice_store import SQLiteInvoiceStore', 'SQLiteInvoiceStore import present'),
    ('payment_store = SQLiteInvoiceStore()', 'SQLiteInvoiceStore instantiated'),
    ('source_tag=804681468', 'source_tag present'),
    ('scheme": "exact"', 'scheme is exact'),
    ('payment_hmac_secret', 'HMAC secret loading present'),
]

print("Verification checks:")
all_ok = True
for pattern, desc in checks:
    found = pattern in content
    print(f"  {'✓' if found else '✗'} {desc}: {found}")
    if not found:
        all_ok = False

# Check NO secret material
secret_patterns = [
    ('secret', 'lowercase secret'),
    ('SEED', 'SEED keyword'),
    ('seed_phrase', 'seed_phrase'),
    ('mnemonic', 'mnemonic'),
    ('private_key', 'private_key'),
    ('PRIVATE_KEY', 'PRIVATE_KEY'),
    ('.env', '.env reference'),
    ('x402-treasury', 'x402-treasury'),
]
print(f"\nSecret material check (should all be ABSENT):")
for pat, desc in secret_patterns:
    found = pat in content
    print(f"  {'✗ FOUND' if found else '✓ ABSENT'} {desc}")
    if found and desc != 'HMAC secret loading present':
        all_ok = False

if all_ok:
    print("\n✓ All verification checks passed")
else:
    print("\n✗ Some verification checks failed — REVIEW REQUIRED")

# Write the file
output_path = "/tmp/italy_bot_server_new.py"
with open(output_path, 'w') as f:
    f.write(content)

print(f"\nFile written: {output_path}")
print(f"Size: {os.path.getsize(output_path)} bytes")

# Compute SHA-256
h = hashlib.sha256(content.encode()).hexdigest()
print(f"SHA-256: {h}")

# Also verify it compiles
result = os.system("/home/xrpladmin/thailand_bot_venv/bin/python -m py_compile " + output_path + " 2>&1")
print(f"Python compile: {'OK' if result == 0 else 'FAILED'}")
